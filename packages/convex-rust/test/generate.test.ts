import { mkdtempSync, mkdirSync, readFileSync, existsSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { generateFiles } from "../src/cli/generate.js";
import { convexModuleName, parseManifest, parseManifestText } from "../src/cli/manifest.js";
import { writeOutput } from "../src/cli/build.js";

const f = (t: any, optional = false) => ({ fieldType: t, optional });
const sample = [
  {
    abiVersion: 1,
    modulePath: "app::hello",
    name: "greet",
    visibility: "public",
    args: {
      type: "object",
      value: {
        name: f({ type: "string" }),
        times: f({ type: "union", value: [{ type: "number" }, { type: "null" }] }, true),
        msg: f({ type: "id", tableName: "messages" }),
        big: f({ type: "bigint" }),
        tags: f({ type: "array", value: { type: "string" } }),
        kind: f({ type: "literal", value: "a" }),
        rec: f({ type: "record", keys: { type: "string" }, values: f({ type: "boolean" }) }),
        raw: f({ type: "bytes" }),
      },
    },
    returns: { type: "object", value: { text: f({ type: "string" }) } },
  },
  { abiVersion: 1, modulePath: "app::hello", name: "noargs", visibility: "public", args: null, returns: null },
  { abiVersion: 1, modulePath: "app::a::b", name: "hidden", visibility: "internal", args: { type: "object", value: {} }, returns: { type: "any" } },
  { abiVersion: 1, modulePath: "app", name: "root", visibility: "public", args: null, returns: null },
] as any[];

describe("module path mapping", () => {
  it("maps crate::a::b -> a/b and crate root -> lib", () => {
    expect(convexModuleName("app::hello")).toBe("hello");
    expect(convexModuleName("app::a::b")).toBe("a/b");
    expect(convexModuleName("app")).toBe("lib");
  });
});

describe("generateFiles", () => {
  const files = generateFiles({ entries: sample, wasmFile: "app.wasm", outRelToFunctions: "rust" });
  it("emits one file per module plus _wasm.d.ts", () => {
    expect([...files.keys()].sort()).toEqual(["_wasm.d.ts", "a/b.ts", "hello.ts", "lib.ts"]);
    for (const t of files.values()) expect(t.startsWith("// @generated by convex-rust. Do not edit.")).toBe(true);
  });
  it("hello.ts: validators, runRust handler, imports", () => {
    const t = files.get("hello.ts")!;
    expect(t).toContain('import { action } from "../_generated/server";');
    expect(t).not.toContain("internalAction");
    expect(t).toContain('import { v } from "convex/values";');
    expect(t).toContain('import { runRust } from "convex-rust/runtime";');
    expect(t).toContain('import wasm from "./_wasm/app.wasm";');
    expect(t).toContain("export const greet = action({");
    expect(t).toContain("name: v.string()");
    expect(t).toContain("times: v.optional(v.union(v.number(), v.null()))");
    expect(t).toContain('msg: v.id("messages")');
    expect(t).toContain("big: v.int64()");
    expect(t).toContain("tags: v.array(v.string())");
    expect(t).toContain('kind: v.literal("a")');
    expect(t).toContain("rec: v.record(v.string(), v.boolean())");
    expect(t).toContain("raw: v.bytes()");
    expect(t).toContain("returns: v.object({ text: v.string() })");
    expect(t).toContain('runRust(ctx, wasm, "convex_run:app::hello:greet", args)');
  });
  it("omitted args default to any (no args validator)", () => {
    const t = files.get("hello.ts")!;
    const block = t.slice(t.indexOf("export const noargs"));
    expect(block).not.toMatch(/^  args:/m);
    expect(block).toContain("(ctx, args: any)");
  });
  it("internal functions use internalAction; nested import paths are relative", () => {
    const t = files.get("a/b.ts")!;
    expect(t).toContain('import { internalAction } from "../../_generated/server";');
    expect(t).toContain('import wasm from "../_wasm/app.wasm";');
    expect(t).toContain('runRust(ctx, wasm, "convex_run:app::a::b:hidden", args)');
    expect(t).toContain("returns: v.any()");
  });
  it("crate root goes to lib.ts", () => {
    expect(files.get("lib.ts")).toContain('"convex_run:app:root"');
  });
  it("a nested out dir changes import depth", () => {
    const m = generateFiles({ entries: sample, wasmFile: "app.wasm", outRelToFunctions: "x/rustv8" });
    expect(m.get("hello.ts")).toContain('from "../../_generated/server"');
    expect(m.get("hello.ts")).toContain('from "./_wasm/app.wasm"');
  });
  it("rejects ECMAScript reserved words as export names", () => {
    for (const name of ["delete", "new", "class", "switch", "import", "default", "yield", "await"]) {
      expect(() =>
        generateFiles({ entries: [{ ...sample[1], name }] as any, wasmFile: "x.wasm" }),
      ).toThrow(/cannot be exported/);
    }
  });
  it("rejects invalid function names", () => {
    expect(() =>
      generateFiles({ entries: [{ ...sample[1], name: "default" }] as any, wasmFile: "x.wasm" }),
    ).toThrow(/cannot be exported/);
  });
});

describe("parseManifest", () => {
  it("rejects unsupported abi and duplicates", () => {
    expect(() => parseManifestText('{"abiVersion":2,"modulePath":"a::b","name":"x"}')).toThrow(/abiVersion/);
    const l = JSON.stringify(sample[1]);
    expect(() => parseManifestText(`${l}\n${l}`)).toThrow(/duplicate/);
    const root = '{"abiVersion":1,"modulePath":"app","name":"x"}';
    const lib = '{"abiVersion":1,"modulePath":"app::lib","name":"y"}';
    expect(() => parseManifestText(`${root}\n${lib}`)).toThrow(/both map to the Convex module `lib`/);
    expect(parseManifestText(lib)).toHaveLength(1);
  });
  it("reads the custom section of a wasm module", () => {
    const text = sample.map((e) => JSON.stringify(e)).join("\n");
    const name = new TextEncoder().encode("convex:manifest");
    const payload = new TextEncoder().encode(text);
    const leb = (n: number) => {
      const o: number[] = [];
      do { let b = n & 127; n >>>= 7; if (n) b |= 128; o.push(b); } while (n);
      return o;
    };
    const body = [...leb(name.length), ...name, ...payload];
    const wasm = new Uint8Array([0, 0x61, 0x73, 0x6d, 1, 0, 0, 0, 0, ...leb(body.length), ...body]);
    expect(parseManifest(wasm).map((e) => e.name)).toEqual(["greet", "noargs", "hidden", "root"]);
  });
});

describe("writeOutput", () => {
  it("writes files and removes stale generated ones", () => {
    const fn = mkdtempSync(path.join(tmpdir(), "cr-"));
    const out = path.join(fn, "rust");
    const w = new Uint8Array([0, 0x61, 0x73, 0x6d, 1, 0, 0, 0]);
    writeOutput(out, "app.wasm", w, sample, fn);
    expect(existsSync(path.join(out, "a/b.ts"))).toBe(true);
    expect(existsSync(path.join(out, "_wasm/app.wasm"))).toBe(true);
    writeOutput(out, "app.wasm", w, sample.slice(0, 2), fn);
    expect(existsSync(path.join(out, "a/b.ts"))).toBe(false);
    expect(existsSync(path.join(out, "lib.ts"))).toBe(false);
    expect(readFileSync(path.join(out, "hello.ts"), "utf8")).toContain("greet");
  });
  it("does not remove hand-written files", () => {
    const fn = mkdtempSync(path.join(tmpdir(), "cr-"));
    const out = path.join(fn, "rust");
    mkdirSync(out, { recursive: true });
    writeFileSync(path.join(out, "mine.ts"), "export {}\n");
    writeOutput(out, "app.wasm", new Uint8Array([0, 0x61, 0x73, 0x6d, 1, 0, 0, 0]), sample, fn);
    expect(existsSync(path.join(out, "mine.ts"))).toBe(true);
  });
});
