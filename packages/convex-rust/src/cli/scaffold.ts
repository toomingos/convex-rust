import fs from "node:fs";
import path from "node:path";
import { RUST_TARGET } from "./toolchain.js";
import { RUST_API_STUB } from "./rustApi.js";
import { managedConfigToml, resolveConvexFnPath } from "./shim.js";

/**
 * Stable Rust is enough for the guest crate (verified with stable 1.99.1: build, run and HTTP action on a
 * stock backend); nothing in convex_fn or the macros needs nightly features. Override with CONVEX_RUST_CHANNEL.
 */
export const DEFAULT_RUST_CHANNEL = "stable";

export interface ScaffoldOptions {
  /** Path to the `convex_fn` crate (env CONVEX_FN_PATH). Unset: registry placeholder. */
  convexFnPath?: string | undefined;
  /** Rust toolchain channel (env CONVEX_RUST_CHANNEL). */
  channel?: string | undefined;
  /** `[build] target-dir` for the generated `.cargo/config.toml`, relative to the crate. */
  targetDir?: string | undefined;
}

/** Cargo target directory kept outside the Convex functions directory (relative to the crate). */
export function defaultTargetDir(projectRoot: string, crateDir: string): string {
  const rel = path.relative(path.resolve(crateDir), path.join(path.resolve(projectRoot), ".convex-rust", "target"));
  return rel.split(path.sep).join("/");
}

function convexFnDependency(rustDir: string, convexFnPath?: string): string {
  if (convexFnPath) {
    let p = path.resolve(convexFnPath);
    const rel = path.relative(path.resolve(rustDir), p);
    if (!path.isAbsolute(rel)) p = rel;
    return `convex_fn = { path = ${JSON.stringify(p.split(path.sep).join("/"))} }`;
  }
  return [
    "# TODO: `convex_fn` is not published yet and was not found in node_modules/convex-rust/rust.",
    "# Set CONVEX_FN_PATH (or pass --convex-fn-path) when running `convex-rust init`, or point this at",
    "# a path/git dependency.",
    'convex_fn = "0.1"',
  ].join("\n");
}

export function scaffoldFiles(rustDir: string, opts: ScaffoldOptions = {}): Record<string, string> {
  const channel = opts.channel ?? DEFAULT_RUST_CHANNEL;
  return {
    "Cargo.toml": `[package]
name = "convex_rust"
edition = "2021"
version = "0.1.0"
publish = false

[lib]
crate-type = ["cdylib"]

[dependencies]
${convexFnDependency(rustDir, opts.convexFnPath ?? resolveConvexFnPath(rustDir))}
serde = { version = "1", features = ["derive"] }
serde_json = "1"

# One wasm per module (smaller cold load on Convex cloud): gate each module with a cargo feature named
# m-<module> and convex-rust build builds one wasm per module. Heavy dependencies go behind it:
#   [features]
#   default = ["m-example", "m-images"]   # default = all, so cargo check sees everything
#   m-example = []
#   m-images = ["dep:image"]              # with image = { version = "0.25", optional = true }
# and in src/lib.rs:  #[cfg(feature = "m-images")] pub mod images;
# See docs/rust/cloud.md.

# Keeps this crate standalone even when the project root is a Cargo workspace.
[workspace]
`,
    "src/lib.rs": `// Each module in this crate becomes a Convex module under \`rust/\`:
// \`src/example.rs\` is called as \`api.rust.example.greet\`.
pub mod example;

// Typed references to your Convex functions, generated by \`convex-rust build\` / \`convex-rust codegen\`.
#[path = "_generated/api.rs"]
pub mod api;
`,
    "src/_generated/api.rs": RUST_API_STUB,
    "src/example.rs": `use convex_fn::{action, ConvexArgs, ConvexValue, Ctx, Result};
use serde::{Deserialize, Serialize};

#[derive(Deserialize, ConvexArgs)]
pub struct GreetArgs {
    pub name: String,
}

#[derive(Serialize, ConvexValue)]
pub struct Greeting {
    pub text: String,
}

/// An example action. Call it as \`api.rust.example.greet({ name: "you" })\`.
/// \`ctx.run_query("module:name", args)\` calls your TypeScript functions.
#[action]
pub async fn greet(_ctx: &Ctx, args: GreetArgs) -> Result<Greeting> {
    Ok(Greeting { text: format!("Hello, {}!", args.name) })
}
`,
    "rust-toolchain.toml": `[toolchain]
channel = ${JSON.stringify(channel)}
targets = ["${RUST_TARGET}"]
components = ["rustfmt", "clippy"]
`,
    ".cargo/config.toml": managedConfigToml({ targetDir: opts.targetDir }),
    // Build outputs. The generated wrappers (*.ts) are small and fine to commit; the wasm is rebuilt by
    // \`convex-rust build\`, so CI must run that before \`convex deploy\`.
    ".gitignore": "# cargo output (only used when target-dir in .cargo/config.toml is removed)\ntarget/\n# compiled wasm, regenerated by `convex-rust build`\n_wasm/\n",
  };
}

export interface ScaffoldResult {
  created: string[];
  skipped: string[];
}

/** Writes the scaffold; never overwrites existing files. */
export function scaffoldRust(rustDir: string, opts: ScaffoldOptions = {}): ScaffoldResult {
  const result: ScaffoldResult = { created: [], skipped: [] };
  for (const [rel, contents] of Object.entries(scaffoldFiles(rustDir, opts))) {
    const full = path.join(rustDir, rel);
    if (fs.existsSync(full)) {
      result.skipped.push(rel);
      continue;
    }
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, contents);
    result.created.push(rel);
  }
  return result;
}
