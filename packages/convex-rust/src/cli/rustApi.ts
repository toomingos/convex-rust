const RELATIVE_API = path.join("src", "_generated", "api.rs");

export function apiRsPath(crateDir: string): string {
  return path.join(crateDir, RELATIVE_API);
}

/** Function paths (`messages:list`) present in an `api.rs`. */
export function functionPathsInApiRs(contents: string): Set<string> {
  const out = new Set<string>();
  for (const m of contents.matchAll(/FunctionRef::new\("([^"]+)"\)/g)) out.add(m[1]);
  return out;
}

export function rustSourcesReferenceApi(crateDir: string): boolean {
  const visit = (dir: string): boolean => {
    let entries: fs.Dirent[];
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      return false;
    }
    for (const e of entries) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) {
        if (e.name !== "_generated" && visit(p)) return true;
      } else if (e.name.endsWith(".rs")) {
        try {
          if (/\bapi\s*::/.test(fs.readFileSync(p, "utf8"))) return true;
        } catch {
          // ignore
        }
      }
    }
    return false;
  };
  return visit(path.join(crateDir, "src"));
}

function writeIfChanged(file: string, text: string): boolean {
  try {
    if (fs.readFileSync(file, "utf8") === text) return false;
  } catch {
    // new
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  return true;
}

export interface ApiRsOptions {
  projectRoot: string;
  functionsDir: string;
  crateDir: string;
  outDir: string;
  /** Rust functions from a previous build (cache) or the fresh manifest. */
  rustEntries?: RustManifestEntry[];
  log?: (m: string) => void;
}

/**
 * Regenerates `<crate>/src/_generated/api.rs` from the TS functions plus the Rust ones. Only
 * runs when the file exists or the Rust sources use `api::`. A failed analysis leaves the file
 * alone. Returns true when the file changed.
 */
export async function updateApiRs(o: ApiRsOptions): Promise<boolean> {
  const file = apiRsPath(o.crateDir);
  const exists = fs.existsSync(file);
  if (!exists && !rustSourcesReferenceApi(o.crateDir)) return false;
  const res = await analyzeTsFunctions(o.projectRoot, o.functionsDir, [o.outDir], 60_000, (m) => o.log?.(m));
  if (res === null) {
    o.log?.("warning: could not analyze the TypeScript functions; leaving src/_generated/api.rs as is");
    if (!exists) writeIfChanged(file, RUST_API_STUB);
    return false;
  }
  for (const w of res.warnings) o.log?.(`warning: ${w}`);
  const outRel = path.relative(o.functionsDir, o.outDir).split(path.sep).join("/");
  const modules = { ...res.modules, ...rustEntriesAsModules(o.rustEntries ?? [], outRel) };
  return writeIfChanged(file, rustApiCodegen(modules));
}

/** Rust functions of the last build, kept in the cargo target dir so the first compile sees them. */
export function readRustCache(cacheFile: string): RustManifestEntry[] {
  try {
    return JSON.parse(fs.readFileSync(cacheFile, "utf8"));
  } catch {
    return [];
  }
}
export function writeRustCache(cacheFile: string, entries: RustManifestEntry[]): void {
  try {
    fs.mkdirSync(path.dirname(cacheFile), { recursive: true });
    fs.writeFileSync(cacheFile, JSON.stringify(entries));
  } catch {
    // best effort
  }
}

