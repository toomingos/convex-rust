/** Runs in the subprocess: prints one JSON line `{ [module]: fn[] }`. */
export const ANALYZE_SCRIPT = `
import { pathToFileURL } from "node:url";
const [dir, ...mods] = process.argv.slice(1);
const out = {};
for (const m of mods) {
  let ns;
  try {
    ns = await import(pathToFileURL(dir + "/" + m).href);
  } catch (e) {
    process.stderr.write("convex-rust: could not load " + m + ": " + (e && e.message || e) + "\\n");
    continue;
  }
  const fns = [];
  for (const [name, f] of Object.entries(ns)) {
    if (typeof f !== "function") continue;
    const udfType = f.isQuery ? "Query" : f.isMutation ? "Mutation" : f.isAction ? "Action" : null;
    if (udfType === null) continue;
    const kind = f.isPublic ? "public" : f.isInternal ? "internal" : null;
    if (kind === null) continue;
    let args = null, returns = null;
    try { args = f.exportArgs(); returns = f.exportReturns(); } catch {}
    fns.push({ name, udfType, visibility: { kind }, args, returns });
  }
  out[m] = fns;
}
process.stdout.write("\\n@@convex-analysis@@" + JSON.stringify(out) + "\\n");
`;

export function parseAnalysisOutput(stdout: string): Record<string, AnalyzedModule> | null {
  const marker = "@@convex-analysis@@";
  const i = stdout.lastIndexOf(marker);
  if (i < 0) return null;
  try {
    const raw = JSON.parse(stdout.slice(i + marker.length).split("\n")[0]) as Record<string, AnalyzedFunction[]>;
    const result: Record<string, AnalyzedModule> = {};
    for (const [mod, functions] of Object.entries(raw)) result[mod] = { functions };
    return result;
  } catch {
    return null;
  }
}

const ENTRY_EXTS = [".js", ".mjs", ".cjs", ".jsx", ".ts", ".mts", ".cts", ".tsx"];
const SKIP_DIRS = new Set(["node_modules", "_generated", "target", "src", "_wasm", ".git"]);

/**
 * TS/JS entry points of the functions directory, following the stock bundler's rules
 * (skips `_generated`, dotfiles, `schema.*`, files with several dots, component directories).
 * `skipDirs` are absolute directories to leave out (e.g. the Rust output directory).
 */
export function findEntryPoints(functionsDir: string, skipDirs: string[] = []): string[] {
  const out: string[] = [];
  const skip = new Set(skipDirs.map((d) => path.resolve(d)));
  const visit = (dir: string) => {
    let entries: fs.Dirent[];
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    entries.sort((a, b) => compareStrings(a.name, b.name));
    for (const e of entries) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) {
        if (SKIP_DIRS.has(e.name) || e.name.startsWith(".") || skip.has(p)) continue;
        if (fs.existsSync(path.join(p, "convex.config.ts"))) continue;
        visit(p);
      } else if (e.isFile()) {
        const base = e.name;
        if (!ENTRY_EXTS.some((x) => base.toLowerCase().endsWith(x))) continue;
        if (base.endsWith(".d.ts") || base.startsWith(".") || base.startsWith("#")) continue;
        if (base === "schema.ts" || base === "schema.js") continue;
        if ((base.match(/\./g) || []).length > 1) continue;
        if (path.relative(functionsDir, p).includes(" ")) continue;
        out.push(p);
      }
    }
  };
  visit(functionsDir);
  return out;
}

function runNode(script: string, args: string[], cwd: string, timeoutMs: number): Promise<{ stdout: string; stderr: string; ok: boolean }> {
  return new Promise((resolve) => {
    const child = spawn(process.execPath, ["--input-type=module", "-e", script, "--", ...args], {
      cwd,
      stdio: ["ignore", "pipe", "pipe"],
      env: process.env,
    });
    let stdout = "";
    let stderr = "";
    child.stdout.setEncoding("utf8");
    child.stdout.on("data", (d: string) => (stdout += d));
    child.stderr.setEncoding("utf8");
    child.stderr.on("data", (d: string) => (stderr += d));
    const timer = setTimeout(() => child.kill("SIGKILL"), timeoutMs);
    child.on("error", () => {
      clearTimeout(timer);
      resolve({ stdout, stderr, ok: false });
    });
    child.on("close", (code) => {
      clearTimeout(timer);
      resolve({ stdout, stderr, ok: code === 0 });
    });
  });
}

async function loadEsbuild(projectRoot: string): Promise<typeof import("esbuild") | null> {
  // Prefer the esbuild that ships with the project's `convex` package.
  try {
    const req = createRequire(path.join(projectRoot, "package.json"));
    const convexDir = path.dirname(req.resolve("convex/package.json"));
    const esb = createRequire(path.join(convexDir, "package.json")).resolve("esbuild");
    return (await import(pathToFileURL(esb).href)).default ?? (await import(pathToFileURL(esb).href));
  } catch {
    // fall through
  }
  try {
    return (await import("esbuild")) as any;
  } catch {
    return null;
  }
}

export interface AnalyzeResult {
  modules: Record<string, AnalyzedModule>;
  warnings: string[];
}

/**
 * Analyzes the TS functions under `functionsDir` without a backend: bundles each module with
 * esbuild (npm packages external, so `convex/server` is the project's), imports the bundles in a
 * Node subprocess and reads each registered function's visibility and validators. Returns null
 * when analysis is not possible (callers keep the existing api.rs).
 */
export async function analyzeTsFunctions(
  projectRoot: string,
  functionsDir: string,
  skipDirs: string[] = [],
  timeoutMs = 60_000,
  log: (m: string) => void = () => {},
): Promise<AnalyzeResult | null> {
  const entries = findEntryPoints(functionsDir, skipDirs);
  if (entries.length === 0) return { modules: {}, warnings: [] };
  const esbuild = await loadEsbuild(projectRoot);
  if (!esbuild) return null;
  // Inside the project so that external imports (`convex/server`) resolve from its node_modules.
  const base = path.join(projectRoot, ".convex-rust");
  fs.mkdirSync(base, { recursive: true });
  const tmp = fs.mkdtempSync(path.join(base, "analysis-"));
  try {
    fs.writeFileSync(path.join(tmp, "package.json"), '{"type":"module"}\n');
    const names = entries.map((p) =>
      path.relative(functionsDir, p).split(path.sep).join("/").replace(/\.[^./]+$/, ""),
    );
    await esbuild.build({
      entryPoints: Object.fromEntries(entries.map((p, i) => [names[i], p])),
      outdir: tmp,
      outExtension: { ".js": ".mjs" },
      bundle: true,
      format: "esm",
      platform: "node",
      packages: "external",
      logLevel: "silent",
      write: true,
      loader: { ".wasm": "empty" },
      absWorkingDir: projectRoot,
      // Per-module failures should not sink the whole run.
      metafile: false,
    }).catch(async (e: any) => {
      // Retry module by module so one broken file does not hide the rest.
      const failed: string[] = [];
      for (let i = 0; i < entries.length; i++) {
        try {
          await esbuild.build({
            entryPoints: { [names[i]]: entries[i] },
            outdir: tmp,
            outExtension: { ".js": ".mjs" },
            bundle: true,
            format: "esm",
            platform: "node",
            packages: "external",
            logLevel: "silent",
            loader: { ".wasm": "empty" },
            absWorkingDir: projectRoot,
          });
        } catch {
          failed.push(names[i]);
        }
      }
      if (failed.length === entries.length) throw e;
      log(`warning: could not bundle ${failed.join(", ")}: ${String(e?.errors?.[0]?.text ?? e?.message ?? e)}`);
    });
    const present = names.filter((n) => fs.existsSync(path.join(tmp, `${n}.mjs`)));
    const { stdout, stderr, ok } = await runNode(
      ANALYZE_SCRIPT,
      [tmp, ...present.map((n) => `${n}.mjs`)],
      projectRoot,
      timeoutMs,
    );
    if (!ok) {
      log(`warning: the analysis process failed: ${stderr.trim().split("\n").slice(-3).join(" | ")}`);
      return null;
    }
    const raw = parseAnalysisOutput(stdout);
    if (raw === null) return null;
    const modules: Record<string, AnalyzedModule> = {};
    for (const [k, v] of Object.entries(raw)) modules[k.replace(/\.mjs$/, ".js")] = v;
    const warnings = stderr
      .split("\n")
      .filter((l) => l.startsWith("convex-rust: could not load"))
      .map((l) => l.replace(/^convex-rust: /, ""));
    for (const n of names) if (!present.includes(n)) warnings.push(`could not bundle ${n}`);
    return { modules, warnings };
  } catch (e: any) {
    const first = e?.errors?.[0];
    const why = first ? `${first.text}${first.location ? ` (${first.location.file}:${first.location.line})` : ""}` : String(e?.message ?? e);
    log(
      `warning: could not bundle the TypeScript functions: ${why}` +
        (/_generated/.test(why) ? " (run `npx convex dev` or `npx convex codegen` once so convex/_generated exists)" : ""),
    );
    return null;
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

/** Rust functions (from the wasm manifest) as analysed modules under `<outRel>/<module>.js`. */
export function rustEntriesAsModules(
  entries: RustManifestEntry[],
  outRel: string,
): Record<string, AnalyzedModule> {
  const mods: Record<string, AnalyzedModule> = {};
  for (const e of entries) {
    // HTTP actions are routed in http.ts, not called through `api`.
    if (e.kind === "http") continue;
    const key = `${outRel ? outRel + "/" : ""}${convexModuleName(e.modulePath)}.js`;
    (mods[key] ??= { functions: [] }).functions.push({
      name: e.name,
      udfType: "Action",
      visibility: { kind: e.visibility },
      args: e.args == null ? null : JSON.stringify(e.args),
      returns: e.returns == null ? null : JSON.stringify(e.returns),
    });
  }
  return mods;
}

