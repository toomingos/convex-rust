// Typed `src/_generated/api.rs`: Rust references to Convex functions for ctx.run_query & co.
// Port of the fork CLI's codegen_templates/rust_api.ts. Instead of the fork's bundler, the TS
// functions are analysed locally with esbuild + a short-lived Node subprocess (no backend).
import fs from "node:fs";
import path from "node:path";
import { spawn } from "node:child_process";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";
import type { RustManifestEntry } from "./manifest.js";
import { convexModuleName } from "./manifest.js";

type ConvexValidator = any;

export interface AnalyzedFunction {
  name: string;
  udfType: string;
  visibility: { kind: "public" | "internal" };
  args: string | null;
  returns: string | null;
}
export interface AnalyzedModule {
  functions: AnalyzedFunction[];
}

const compareStrings = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

export const RUST_API_HEADER = `// @generated by \`convex-rust\`. Do not edit; changes are overwritten.
//
// Typed references to your Convex functions for \`ctx.run_query\`,
// \`ctx.run_mutation\` and \`ctx.run_action\`. Include it from \`lib.rs\` with
//
//     #[path = "_generated/api.rs"]
//     pub mod api;
#![allow(
    non_upper_case_globals,
    non_snake_case,
    non_camel_case_types,
    dead_code,
    unused_imports,
    clippy::all
)]
`;

/** Placeholder `api.rs` until the first codegen fills it in. */
export const RUST_API_STUB = `${RUST_API_HEADER}
// No functions yet: this file is filled in by the next \`convex-rust build\` or \`convex-rust codegen\`.
`;

